#[test]
fn test_identity_format_roundtrip() {
    // Verify that we can parse the identity from Go signature and reconstruct the public key

    // Ed25519
    let ed25519_identity_hex =
        "d75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a";
    let ed25519_key_bytes = hex::decode(ed25519_identity_hex).expect("Should decode hex");
    let ed25519_pubkey =
        Ed25519PublicKey::from_bytes(&ed25519_key_bytes).expect("Should parse Ed25519 key");
    assert_eq!(
        ed25519_pubkey.to_hex_string(),
        ed25519_identity_hex,
        "Ed25519 identity should roundtrip"
    );

    // secp256k1
    let secp256k1_identity_hex =
        "0284bf7562262bbd6940085748f3be6afa52ae317155181ece31b66351ccffa4b0";
    let secp256k1_key_bytes = hex::decode(secp256k1_identity_hex).expect("Should decode hex");
    let secp256k1_pubkey = Secp256k1PublicKey::from_bytes(&secp256k1_key_bytes)
        .expect("Should parse secp256k1 key");
    assert_eq!(
        secp256k1_pubkey.to_hex_string(),
        secp256k1_identity_hex,
        "secp256k1 identity should roundtrip"
    );
}
