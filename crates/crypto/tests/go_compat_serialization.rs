#[test]
fn test_rust_signature_format_matches_go_ed25519() {
    // Sign the same block bytes with the same key
    let block_bytes = hex::decode(MERKLE_TEST_BLOCK_CBOR).expect("Should decode block hex");
    let private_key = Ed25519PrivateKey::from_bytes(&ED25519_PRIVATE_KEY).unwrap();

    // Create signature the same way Go does
    let signature_value = private_key.sign(&block_bytes).unwrap();

    // Identity should be hex-encoded public key string as bytes (Go format)
    let identity = private_key.public_key().to_hex_string().into_bytes();

    let rust_signature = Signature {
        header: SignatureHeader {
            sig_type: SignatureType::EdDSA,
            identity,
        },
        value: signature_value,
    };

    // Serialize to DAG-CBOR
    let rust_sig_bytes =
        serde_ipld_dagcbor::to_vec(&rust_signature).expect("Should serialize signature");

    // Decode Go signature for comparison
    let go_sig_bytes = hex::decode(ED25519_SIG_BLOCK_CBOR).expect("Should decode Go sig");

    // The serialized bytes should match exactly
    assert_eq!(
        rust_sig_bytes, go_sig_bytes,
        "Rust-generated Ed25519 signature block should match Go format exactly"
    );
}

